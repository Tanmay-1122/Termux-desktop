#!/data/data/com.termux/files/usr/bin/bash

# ============================================================
#   Termux Desktop Launcher
#   Usage:
#     startdesktop              -> Termux:X11 (recommended)
#     startdesktop rdp          -> xRDP mode
#     startdesktop novnc        -> noVNC browser mode
#     startdesktop menu         -> show selection menu
#     startdesktop stop         -> kill all desktop sessions
#     startdesktop --nogpu      -> disable GPU acceleration
#     startdesktop --legacy     -> use legacy X11 drawing
#     startdesktop --nodbus     -> start without dbus-launch
#     startdesktop --debug      -> show startup logs
#     startdesktop --help       -> show help
#   Repo : github.com/Tanmay-1122/Termux-desktop
# ============================================================

set -eo pipefail

export PREFIX="${PREFIX:-/data/data/com.termux/files/usr}"
export HOME="${HOME:-/data/data/com.termux/files/home}"
export TMPDIR="${TMPDIR:-$PREFIX/tmp}"
export PATH="$PREFIX/bin:/system/bin:/system/xbin:$PATH"

# ── Colors ───────────────────────────────────────────────────
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
CYAN='\033[0;36m'
BOLD='\033[1m'
DIM='\033[2m'
NC='\033[0m'

# ── Config file ──────────────────────────────────────────────
CONFIG_DIR="$PREFIX/etc/termux-desktop"
CONFIG_FILE="$CONFIG_DIR/configuration.conf"

load_config() {
    if [ -f "$CONFIG_FILE" ]; then
        source "$CONFIG_FILE" 2>/dev/null || true
    fi
}

save_config() {
    mkdir -p "$CONFIG_DIR" 2>/dev/null
    cat > "$CONFIG_FILE" << CONF
# Termux Desktop Configuration
PROJECT_VER=$(cat "$HOME/.termux-desktop-version" 2>/dev/null || echo "1.4")
# Generated by start-desktop
DESKTOP_MODE=${MODE:-x11}
DISPLAY_NUM=${DISPLAY_NUM:-0}
NOGPU=${NOGPU:-false}
LEGACY=${LEGACY:-false}
NODBUS=${NODBUS:-false}
CONF
}

# ── GPU Detection ────────────────────────────────────────────
detect_gpu() {
    local gpu="unknown"
    local chipset=$(getprop ro.hardware 2>/dev/null || true)
    local board=$(getprop ro.board.platform 2>/dev/null || true)
    if echo "$chipset $board" | grep -qi "qcom\|msm\|snapdragon"; then gpu="adreno"
    elif echo "$chipset $board" | grep -qi "mali\|arm\|exynos"; then gpu="mali"
    elif echo "$chipset $board" | grep -qi "xclipse"; then gpu="xclipse"
    fi
    echo "$gpu"
}

# ── GPU Environment ──────────────────────────────────────────
setup_gpu_env() {
    if [ "$NOGPU" = "true" ]; then
        echo "[*] GPU acceleration disabled (--nogpu)"
        return
    fi
    local gpu=$(detect_gpu)
    if command -v virgl_test_server_android &>/dev/null; then
        echo "[*] Initializing VirGL GPU acceleration (GPU: $gpu)..."
        virgl_test_server_android &>/dev/null &
        sleep 1
        if pgrep -f virgl_test_server &>/dev/null; then
            export GALLIUM_DRIVER=virpipe
            export MESA_GL_VERSION_OVERRIDE=4.3COMPAT
            export MESA_GLES_VERSION_OVERRIDE=3.2
            export MESA_NO_ERROR=1
            echo "[OK] VirGL acceleration active (GPU: $gpu)"
        else
            echo "[!] VirGL failed to start. Using software rendering."
        fi
    elif [ "$gpu" = "adreno" ] && command -v vulkaninfo &>/dev/null; then
        export GALLIUM_DRIVER=zink
        export MESA_GL_VERSION_OVERRIDE=4.3COMPAT
        export ZINK_DESCRIPTORS=lazy
        echo "[OK] Zink/Vulkan acceleration active (GPU: $gpu)"
    else
        echo "[!] No GPU acceleration available (GPU: $gpu). Software rendering."
    fi
}

# ── IP Helpers ───────────────────────────────────────────────
get_ip() {
    local iface="$1"
    local addr=""
    if command -v ip &>/dev/null; then
        addr=$(ip addr show "$iface" 2>/dev/null \
               | grep -oE 'inet [0-9.]+' | awk '{print $2}' | head -1)
    fi
    if [ -z "$addr" ] && command -v ifconfig &>/dev/null; then
        addr=$(ifconfig "$iface" 2>/dev/null | grep 'inet ' | awk '{print $2}' | head -1)
    fi
    echo "$addr"
}

list_all_ips() {
    local ips=""
    if command -v ip &>/dev/null; then
        ips=$(ip -4 addr show | grep -oE 'inet [0-9.]+' | awk '{print $2}' | grep -v '^127\.')
    elif command -v ifconfig &>/dev/null; then
        ips=$(ifconfig | grep -oE 'inet [0-9.]+' | awk '{print $2}' | grep -v '^127\.')
    fi
    echo "$ips"
}

detect_best_ip() {
    local route_ip=""
    if command -v ip &>/dev/null; then
        route_ip=$(ip route get 8.8.8.8 2>/dev/null | grep -oP 'src \K[\d.]+' | head -1)
    fi
    if [ -n "$route_ip" ]; then echo "$route_ip"; return; fi

    if command -v hostname &>/dev/null; then
        local host_ip=$(hostname -I 2>/dev/null | awk '{print $1}')
        if [ -n "$host_ip" ]; then echo "$host_ip"; return; fi
    fi

    local first=$(list_all_ips | head -1)
    if [ -n "$first" ]; then echo "$first"; return; fi

    echo ""
}

WIFI_IP=""
USB_IP=""
USB_IFACE=""

for iface in wlan0 wlan1 ccmni0; do
    IP=$(get_ip "$iface")
    if [ -n "$IP" ]; then WIFI_IP="$IP"; break; fi
done

for iface in rndis0 usb0 eth0 rmnet_usb0; do
    IP=$(get_ip "$iface")
    if [ -n "$IP" ]; then USB_IP="$IP"; USB_IFACE="$iface"; break; fi
done

BEST_IP="${WIFI_IP:-$USB_IP}"
if [ -z "$BEST_IP" ]; then
    BEST_IP=$(detect_best_ip)
fi

# ── Argument Parsing ─────────────────────────────────────────
MODE="x11"
DISPLAY_NUM=0
NOGPU=false
LEGACY=false
NODBUS=false
DEBUG=false

show_help() {
    cat << 'HELP'
Usage: startdesktop [MODE] [OPTIONS]

Modes:
  (none)       Start Termux:X11 (default, recommended)
  rdp          Start xRDP (connect via Windows Remote Desktop)
  novnc        Start noVNC (browser-based access)
  menu         Show interactive mode selection
  stop         Kill all desktop sessions

Options:
  --nogpu      Disable GPU hardware acceleration
  --legacy     Use legacy X11 drawing (-legacy-drawing)
  --nodbus     Start without dbus-launch wrapper
  --debug      Show startup logs and commands
  --help,-h    Show this help message

Network:
  RDP address  <IP>:3389  (shown in menu/mode banners)
  noVNC URL    http://<IP>:6080/vnc.html

Examples:
  startdesktop                  # GPU-accelerated X11 session
  startdesktop --nogpu          # Software rendering
  startdesktop rdp              # xRDP mode (auto-detects IP)
  startdesktop novnc            # Browser mode (auto-detects IP)
  startdesktop menu             # Interactive menu
  startdesktop stop             # Kill everything

HELP
    exit 0
}

while [ $# -gt 0 ]; do
    case "$1" in
        x11|X11|"")       MODE="x11" ;;
        rdp|RDP)           MODE="rdp" ;;
        novnc|noVNC)       MODE="novnc" ;;
        menu)              MODE="menu" ;;
        stop|kill)         MODE="stop" ;;
        --nogpu)           NOGPU=true ;;
        --legacy)          LEGACY=true ;;
        --nodbus)          NODBUS=true ;;
        --debug)           DEBUG=true ;;
        --help|-h)         show_help ;;
        *)                 echo "[!] Unknown option '$1'. Use --help."; exit 1 ;;
    esac
    shift
done

debug_log() {
    if [ "$DEBUG" = "true" ]; then
        echo -e "${DIM}[DEBUG] $1${NC}"
    fi
}

# ── Stop Mode ────────────────────────────────────────────────
if [ "$MODE" = "stop" ]; then
    echo "[*] Stopping all desktop sessions..."
    pkill xrdp 2>/dev/null || true
    pkill xrdp-sesman 2>/dev/null || true
    pkill Xtigervnc 2>/dev/null || true
    pkill Xvnc 2>/dev/null || true
