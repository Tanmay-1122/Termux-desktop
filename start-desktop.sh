# ════════════════════════════════════════════════════════════
# Shared Helpers
# ════════════════════════════════════════════════════════════
setup_xsession() {
    export XDG_RUNTIME_DIR="$PREFIX/tmp/runtime-$UID"
    mkdir -p "$XDG_RUNTIME_DIR"
    chmod 700 "$XDG_RUNTIME_DIR"
    cat > ~/.xsession << 'EOL'
export XDG_RUNTIME_DIR=/data/data/com.termux/files/usr/tmp/runtime-0
mkdir -p $XDG_RUNTIME_DIR
chmod 700 $XDG_RUNTIME_DIR
dbus-launch --exit-with-session xfce4-session
EOL
    chmod +x ~/.xsession
    echo "startxfce4" > ~/.Xclients
    chmod +x ~/.Xclients
}

configure_xrdp() {
    local XRDP_INI="$PREFIX/etc/xrdp/xrdp.ini"
    [ ! -f "$XRDP_INI" ] && return 1
    sed -i 's/^autorun=.*/autorun=Direct-VNC/' "$XRDP_INI"
    grep -q '^autorun=' "$XRDP_INI" || \
        sed -i '/^\[Globals\]/a autorun=Direct-VNC' "$XRDP_INI"
    sed -i 's/^crypt_level=high/crypt_level=none/' "$XRDP_INI"
    grep -q '\[Direct-VNC\]' "$XRDP_INI" || cat >> "$XRDP_INI" << 'XEOF'

[Direct-VNC]
name=NoLogin
lib=libvnc.so
username=na
password=na
ip=127.0.0.1
port=5901
XEOF
}

start_vnc() {
    echo "[*] Starting VNC on :1 (port 5901)..."
    vncserver :1 -geometry 1366x768 -depth 24 \
        -SecurityTypes None -localhost no 2>/dev/null
    sleep 2
    if ! pgrep -f "Xvnc.*:1" >/dev/null && ! pgrep -f "Xtigervnc.*:1" >/dev/null; then
        echo "[!!] VNC failed. Check: ~/.vnc/"
        exit 1
    fi
    echo "[OK] VNC running on :1"
}

_wait_for_session() {
    local pid="$1" label="$2" max_wait="${3:-10}"
    local waited=0
    while [ $waited -lt $max_wait ]; do
        if kill -0 "$pid" 2>/dev/null; then
            if pgrep -f "xfce4-session" >/dev/null 2>&1; then
                return 0
            fi
        else
            echo "[!] $label failed to start (process exited)"
            return 1
        fi
        sleep 1
        waited=$((waited + 1))
    done
    echo "[!] $label did not start within ${max_wait}s — check installation"
    return 1
}

_start_picom() {
    if command -v picom &>/dev/null; then
        local picom_conf="$HOME/.config/picom/picom.conf"
        if [ -f "$picom_conf" ]; then
            picom --config "$picom_conf" -b >/dev/null 2>&1 &
            echo "[OK] Picom compositor started (blur enabled)"
        else
            picom -b >/dev/null 2>&1 &
            echo "[OK] Picom compositor started (default config)"
        fi
    else
        echo "[!] Picom not installed — blur unavailable."
    fi
}

# ════════════════════════════════════════════════════════════
# MODE X11 — Termux:X11
# ════════════════════════════════════════════════════════════
start_x11() {
    echo ""
    echo "[*] Starting Termux:X11 mode..."
    termux-wake-lock 2>/dev/null || true

    pulseaudio --start \
        --load="module-native-protocol-tcp auth-ip-acl=127.0.0.1 auth-anonymous=1" \
        --exit-idle-time=-1 2>/dev/null || true

    export XDG_RUNTIME_DIR="${TMPDIR:-$PREFIX/tmp}"
    mkdir -p "$XDG_RUNTIME_DIR/.X11-unix"
    chmod 1777 "$XDG_RUNTIME_DIR/.X11-unix" 2>/dev/null || true

    local X11_ARGS=""
    [ "$LEGACY" = "true" ] && X11_ARGS="$X11_ARGS -legacy-drawing"
    debug_log "termux-x11 :0 $X11_ARGS"
    termux-x11 :0 $X11_ARGS >/dev/null 2>&1 &
    sleep 4

    echo "[*] Launching Termux:X11 app..."
    if command -v am &>/dev/null; then
        if am start --user 0 \
            -n com.termux.x11/com.termux.x11.MainActivity \
            >/dev/null 2>&1; then
            echo "[OK] Termux:X11 app launched"
        else
            echo "[!!] Could not launch automatically — open Termux:X11 manually"
        fi
    else
        echo "[!] Please open the Termux:X11 app on your phone."
    fi
    sleep 2

    export PULSE_SERVER=127.0.0.1
    export DISPLAY=:0
    export TMPDIR="$PREFIX/tmp"

    local STARTUP_CMD="xfce4-session"
    local DBUS_CMD=""
    if [ "$NODBUS" = "false" ]; then
        DBUS_CMD="dbus-launch --exit-with-session"
    else
        DBUS_CMD="exec"
    fi

    echo ""
    echo "╔══════════════════════════════════════════════════╗"
    echo "║       Termux:X11  MODE  ACTIVE                  ║"
    echo "╠══════════════════════════════════════════════════╣"
    echo "║   Termux:X11 app should show your desktop       ║"
    echo "║   XFCE4 is launching — please wait a moment     ║"
    echo "║   Press Ctrl+C to stop                          ║"
    echo "╚══════════════════════════════════════════════════╝"
    echo ""

    debug_log "Command: $DBUS_CMD $STARTUP_CMD"
    $DBUS_CMD $STARTUP_CMD >/dev/null 2>&1 &
    XFCE_PID=$!
    _wait_for_session "$XFCE_PID" "XFCE4 session" 10 || true
    _start_picom
    wait $XFCE_PID
}

# ════════════════════════════════════════════════════════════
# MODE RDP — xRDP
# ════════════════════════════════════════════════════════════
start_rdp() {
    echo ""
    echo "[*] Starting xRDP mode..."
    if ! command -v xrdp &>/dev/null; then
        echo "[!] xRDP not installed. Installing..."
        if ! pkg install -y xrdp 2>/dev/null; then
            echo "[!!] Failed to install xrdp. Try: pkg install xrdp"
            exit 1
        fi
        echo "[OK] xrdp installed"
    fi

    termux-wake-lock 2>/dev/null || true
    setup_xsession
    configure_xrdp
    start_vnc

    echo "[*] Launching XFCE4..."
    export DISPLAY=:1
    dbus-launch --exit-with-session xfce4-session \
        > "$PREFIX/tmp/xfce4.log" 2>&1 &
    XFCE_PID=$!
    _wait_for_session "$XFCE_PID" "XFCE4 session" 10 || true
    _start_picom

    echo "[*] Starting xRDP on port 3389..."
    xrdp-sesman > "$PREFIX/tmp/xrdp-sesman.log" 2>&1 &
    sleep 1
    xrdp > "$PREFIX/tmp/xrdp.log" 2>&1 &
    sleep 2

    if ! pgrep -x "xrdp" >/dev/null; then
        echo "[!!] xRDP failed. Log:"; cat "$PREFIX/tmp/xrdp.log"
        exit 1
    fi
    echo "[OK] xRDP running on port 3389"

    echo ""
    echo "╔══════════════════════════════════════════════════╗"
    echo "║           xRDP  MODE  ACTIVE                    ║"
    echo "╠══════════════════════════════════════════════════╣"
    echo "║   Connect using Windows Remote Desktop (mstsc)  ║"
    echo "║                                                  ║"
    [ -n "$WIFI_IP" ] && printf "║   WiFi  → %-37s║\n" "$WIFI_IP:3389"
    [ -n "$USB_IP"  ] && printf "║   USB   → %-37s║\n" "$USB_IP:3389"
    [ -z "$WIFI_IP" ] && [ -z "$USB_IP" ] && \
        echo "║   No IP detected — check connection             ║"
    echo "║                                                  ║"
    echo "║   Leave username/password blank                  ║"
    echo "║   Press Ctrl+C to stop                           ║"
    echo "╚══════════════════════════════════════════════════╝"
    echo ""
    wait $XFCE_PID
}

# ════════════════════════════════════════════════════════════
# MODE NOVNC — browser access
# ════════════════════════════════════════════════════════════
start_novnc() {
    echo ""
    echo "[*] Starting noVNC mode..."
    termux-wake-lock 2>/dev/null || true

    command -v websockify &>/dev/null || {
        echo "[*] Installing websockify..."
        pkg install -y websockify || { echo "[!!] websockify install failed"; exit 1; }
    }

    NOVNC_DIR="$HOME/noVNC"
    if [ ! -d "$NOVNC_DIR" ]; then
        echo "[*] Downloading noVNC web client..."
        local novnc_url="https://github.com/novnc/noVNC/archive/refs/heads/master.zip"
        local novnc_zip="$TMPDIR/novnc.zip"
        if command -v aria2c &>/dev/null; then
            aria2c -x 4 -s 4 --connect-timeout=10 --timeout=30 \
                --max-tries=3 --retry-wait=2 \
                --allow-overwrite=true --auto-file-renaming=false \
                "$novnc_url" -d "$TMPDIR" -o "novnc.zip" \
                -q 2>/dev/null || true
        fi
        if [ ! -f "$novnc_zip" ] || [ ! -s "$novnc_zip" ]; then
            wget -c -q "$novnc_url" -O "$novnc_zip" || true
        fi
        [ -f "$novnc_zip" ] && unzip -q "$novnc_zip" -d "$HOME" && \
        mv "$HOME/noVNC-master" "$NOVNC_DIR" && \
        rm -f "$novnc_zip" || true
    fi

    setup_xsession
    start_vnc

    echo "[*] Launching XFCE4..."
    export DISPLAY=:1
    dbus-launch --exit-with-session xfce4-session \
        > "$PREFIX/tmp/xfce4.log" 2>&1 &
    XFCE_PID=$!
    _wait_for_session "$XFCE_PID" "XFCE4 session" 10 || true
    _start_picom

    echo "[*] Starting websockify on port 6080..."
    if [ -d "$NOVNC_DIR" ]; then
        websockify --web="$NOVNC_DIR" 6080 localhost:5901 \
             > "$PREFIX/tmp/websockify.log" 2>&1 &
    else
        websockify 6080 localhost:5901 \
             > "$PREFIX/tmp/websockify.log" 2>&1 &
    fi
    sleep 2

    echo ""
    echo "╔══════════════════════════════════════════════════╗"
    echo "║           noVNC  MODE  ACTIVE                   ║"
    echo "╠══════════════════════════════════════════════════╣"
    echo "║   Open in any browser on your network:          ║"
    echo "║                                                  ║"
    [ -n "$WIFI_IP" ] && printf "║   http://%-40s║\n" "$WIFI_IP:6080/vnc.html"
    [ -n "$USB_IP"  ] && printf "║   http://%-40s║\n" "$USB_IP:6080/vnc.html"
    [ -z "$BEST_IP" ] && \
        echo "║   No IP detected — check WiFi                   ║"
    echo "║                                                  ║"
    echo "║   Works on Windows, Mac, Linux, iOS, Android    ║"
    echo "║   No app needed — just a browser                ║"
    echo "║   Press Ctrl+C to stop                           ║"
    echo "╚══════════════════════════════════════════════════╝"
    echo ""
    wait $XFCE_PID
}

