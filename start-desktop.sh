    pkill -f virgl_test_server 2>/dev/null || true
    rm -rf "$PREFIX/tmp/.X"* 2>/dev/null || true
    rm -rf "$PREFIX/tmp/.X11-unix/"* 2>/dev/null || true
    echo "[OK] Desktop stopped."
    exit 0
fi

